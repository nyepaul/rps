$ErrorActionPreference = "Stop"

Set-Location (Join-Path $PSScriptRoot "..")

$envFile = Join-Path (Get-Location) ".env"
$hostPort = $env:RPS_HOST_PORT
if (-not $hostPort) { $hostPort = "5137" }

function Require-Cmd($name) {
  if (-not (Get-Command $name -ErrorAction SilentlyContinue)) {
    throw "ERROR: '$name' not found on PATH."
  }
}

Require-Cmd "docker"

try {
  docker compose version | Out-Null
} catch {
  throw "ERROR: 'docker compose' is not available (Docker Desktop / compose v2 required)."
}

if (Test-Path $envFile) {
  Write-Host "[setup] .env already exists; leaving it unchanged: $envFile"
} else {
  Write-Host "[setup] creating .env"
  Write-Host "[setup] generating SECRET_KEY and ENCRYPTION_KEY using Docker (no host deps)..."

  $py = @"
import secrets, string
alphabet = string.ascii_letters + string.digits + "!@#$%^&*()-_=+"
def gen(n=64):
    return "".join(secrets.choice(alphabet) for _ in range(n))
print("SECRET_KEY=" + gen())
print("ENCRYPTION_KEY=" + gen())
"@

  $secrets = docker run --rm python:3.11-slim python -c $py

  @"
# RPS localhost Docker install (.env)
# Generated by bin/docker-setup.ps1
$secrets
"@ | Set-Content -Path $envFile -Encoding ASCII

  Write-Host "[setup] wrote $envFile"
}

Write-Host "[setup] starting services (redis + rps) on http://127.0.0.1:$hostPort"
docker compose up -d

Write-Host "[setup] done"
Write-Host "Next:"
Write-Host "  - View logs: docker compose logs -f rps"
Write-Host "  - Stop:      docker compose down"
